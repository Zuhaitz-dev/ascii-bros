#!/usr/bin/env python3
"""Generate 32 original ascii-bros level maps."""
from pathlib import Path

OUT = Path("levels")
OUT.mkdir(exist_ok=True)

def d(w, items=None):
    r = ['.'] * w
    for c, ch in (items or {}).items():
        if 0 <= c < w:
            r[c] = ch
    return ''.join(r).rstrip('.')

def g(w, gaps=(), ch='='):
    r = [ch] * w
    for s, n in gaps:
        for i in range(n):
            if 0 <= s + i < w:
                r[s + i] = ' '
    return ''.join(r).rstrip()

def fp(w, fc, row, extra=None):
    it = dict(extra or {})
    if row == 3:
        it[fc - 1] = '>'; it[fc] = '|'
    elif 4 <= row <= 10:
        it[fc] = '|'
    return d(w, it)

def fpg(w, fc, gaps=()):
    r = list(g(w, gaps))
    while len(r) <= fc:
        r.append('=')
    r[fc] = 'X'
    return ''.join(r).rstrip()

def cg(w, gaps=()):
    return g(w, gaps, 'X')

def save(world, level, rows):
    assert len(rows) == 13, f"W{world}-{level}: need 13 rows, got {len(rows)}"
    (OUT / f"world_{world}_{level}.map").write_text('\n'.join(rows) + '\n')
    print(f"  world_{world}_{level}.map")

